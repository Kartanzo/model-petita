#!/usr/bin/env node
/* Reads produtos.json (already deduped) and replaces the products INSERT block
   in db/full-schema.sql between sentinels:
     -- BEGIN_PRODUCTS_SEED
     -- END_PRODUCTS_SEED
   If sentinels are absent, replaces the first INSERT INTO petita.products ... ;
*/
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const JSON_PATH = path.join(ROOT, 'produtos.json');
const SCHEMA_PATH = path.join(ROOT, 'db', 'full-schema.sql');

const products = JSON.parse(fs.readFileSync(JSON_PATH, 'utf-8'));

function esc(s) { return String(s ?? '').replace(/'/g, "''"); }
function code(linha, nome) {
  const prefix = (linha || 'PRD').split('-').map(p => p.slice(0, 3)).join('').toUpperCase().slice(0, 6);
  const suf = String(nome || '').replace(/[^a-z0-9]/gi, '').toUpperCase().slice(0, 12);
  return `${prefix}-${suf}`;
}
function pretty(s) { return String(s || '').replace(/[-_]/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase()).trim(); }
function priceFor(linha) {
  if (/premium/i.test(linha)) return [45, 120];
  if (/basic|simples/i.test(linha)) return [12, 35];
  return [20, 75];
}

// dedupe code suffixes
const codes = new Set();
const rows = products.map((p) => {
  let c = code(p.linha, p.nome); let i = 1;
  while (codes.has(c)) { c = `${code(p.linha, p.nome)}${i++}`; }
  codes.add(c);
  const [lo, hi] = priceFor(p.linha);
  const price = +(lo + Math.random() * (hi - lo)).toFixed(2);
  const cost = +(price * (0.45 + Math.random() * 0.2)).toFixed(2);
  const specs = {
    volume_ml: 60 + Math.round(Math.random() * 240),
    idade: ['0-6m', '6-12m', '12-24m', '0-3a'][Math.floor(Math.random() * 4)],
    material: ['Polipropileno BPA-free', 'Silicone medicinal', 'PP+TR', 'Algodão orgânico'][Math.floor(Math.random() * 4)],
    peso_g: 40 + Math.round(Math.random() * 160),
    dimensoes_cm: `${10 + Math.round(Math.random() * 15)}x${4 + Math.round(Math.random() * 6)}x${4 + Math.round(Math.random() * 6)}`,
  };
  return `('${c}','${esc(pretty(p.nome))}',(SELECT id FROM petita.product_families WHERE slug='${esc(p.linha)}'),'${esc(p.descricao || '')}','${esc(JSON.stringify(specs))}'::jsonb,${cost},${price},'UN','/${esc(p.image_local)}',TRUE)`;
});

const insertBlock = [
  '-- BEGIN_PRODUCTS_SEED',
  '-- AUTO-GENERATED by scripts/gen-products-sql.js — do not edit by hand',
  '',
  '-- Limpeza única e definitiva de produtos legados (gated por flag em petita.config)',
  'DO $$',
  'BEGIN',
  "  IF NOT EXISTS (SELECT 1 FROM petita.config WHERE key='products_seeded_v2') THEN",
  '    DELETE FROM petita.quote_items;',
  '    DELETE FROM petita.order_items;',
  '    TRUNCATE petita.products RESTART IDENTITY CASCADE;',
  '  END IF;',
  'END$$;',
  '',
  'INSERT INTO petita.products (code,name,family_id,description,technical_specs,cost,price,unit,photo_url,active) VALUES',
  rows.join(',\n'),
  'ON CONFLICT (code) DO UPDATE SET',
  '  name = EXCLUDED.name,',
  '  family_id = EXCLUDED.family_id,',
  '  description = EXCLUDED.description,',
  '  technical_specs = EXCLUDED.technical_specs,',
  '  cost = EXCLUDED.cost,',
  '  price = EXCLUDED.price,',
  '  unit = EXCLUDED.unit,',
  '  photo_url = EXCLUDED.photo_url,',
  '  active = EXCLUDED.active,',
  '  updated_at = now();',
  '',
  "INSERT INTO petita.config (key,value) VALUES ('products_seeded_v2','{\"done\":true}'::jsonb)",
  'ON CONFLICT (key) DO NOTHING;',
  '-- END_PRODUCTS_SEED',
].join('\n');

let schema = fs.readFileSync(SCHEMA_PATH, 'utf-8');
const sentinelRe = /-- BEGIN_PRODUCTS_SEED[\s\S]*?-- END_PRODUCTS_SEED/;
if (sentinelRe.test(schema)) {
  schema = schema.replace(sentinelRe, insertBlock);
} else {
  // replace first INSERT INTO petita.products ... ;
  schema = schema.replace(/INSERT INTO petita\.products[\s\S]*?ON CONFLICT[^;]*;/i, insertBlock);
}
fs.writeFileSync(SCHEMA_PATH, schema);
console.log(`Wrote ${rows.length} product rows to ${SCHEMA_PATH}`);
